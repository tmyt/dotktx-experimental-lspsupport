using System.Text;
using System.Text.Json;
using System.Text.Json.Nodes;

namespace DotKtx.Experimental.LspSupport;

internal static class WorkspaceWriter
{
    private const string ModulePrefix = "DotKtx.Experimental.LspSupport:";

    public static void Generate(
        string projectDirectory,
        string projectName,
        string outputDirectory,
        IReadOnlyList<string> sources,
        string? builtinsJar,
        ProjectionResult projection,
        JavaStubProjection javaProjection,
        string report)
    {
        Directory.CreateDirectory(outputDirectory);
        var stubsDirectory = Path.Combine(outputDirectory, "stubs");
        Directory.CreateDirectory(stubsDirectory);

        var expected = new HashSet<string>(StringComparer.Ordinal);
        foreach (var (relativePath, contents) in projection.Files)
        {
            var path = Path.GetFullPath(Path.Combine(stubsDirectory, relativePath));
            if (!path.StartsWith(Path.GetFullPath(stubsDirectory) + Path.DirectorySeparatorChar, StringComparison.Ordinal))
                throw new InvalidDataException($"projected path escapes stub root: {relativePath}");
            expected.Add(path);
            WriteTextIfDifferent(path, contents);
        }

        foreach (var existing in Directory.EnumerateFiles(stubsDirectory, "*.kt", SearchOption.AllDirectories))
            if (!expected.Contains(Path.GetFullPath(existing)))
                File.Delete(existing);
        RemoveEmptyDirectories(stubsDirectory);

        var librariesDirectory = Path.Combine(outputDirectory, "libraries");
        var javaStubJar = Path.Combine(librariesDirectory, "dotkt-klib-java-stubs.jar");
        WriteBytesIfDifferent(javaStubJar, javaProjection.Jar);

        WriteTextIfDifferent(Path.Combine(outputDirectory, "projection-report.md"), report);
        WriteTextIfDifferent(
            Path.Combine(outputDirectory, "README.md"),
            "# Generated DotKt LSP model\n\n" +
            "This directory is generated by `DotKtx.Experimental.LspSupport`. " +
            "Its Kotlin sources and Java class archive are analysis-only declarations and must never be compiled or executed by DotKt.\n");
        WriteTextIfDifferent(Path.Combine(Path.GetDirectoryName(outputDirectory)!, ".gitignore"), "*\n");

        var workspacePath = Path.Combine(projectDirectory, "workspace.json");
        EnsureWorkspaceIsOurs(workspacePath);
        var workspace = BuildWorkspace(
            projectDirectory,
            projectName,
            outputDirectory,
            sources,
            builtinsJar,
            javaStubJar);
        WriteTextIfDifferent(
            workspacePath,
            workspace.ToJsonString(new JsonSerializerOptions { WriteIndented = true }) + "\n");

        // The stamp is intentionally refreshed whenever MSBuild decided the target was stale.
        File.WriteAllText(Path.Combine(outputDirectory, ".stamp"), DateTime.UtcNow.ToString("O") + "\n");
    }

    public static void Clean(string projectDirectory, string outputDirectory)
    {
        if (Directory.Exists(outputDirectory)) Directory.Delete(outputDirectory, recursive: true);
        var dotktDirectory = Path.GetDirectoryName(outputDirectory);
        if (dotktDirectory is not null && Directory.Exists(dotktDirectory) &&
            !Directory.EnumerateFileSystemEntries(dotktDirectory).Any())
            Directory.Delete(dotktDirectory);

        var workspacePath = Path.Combine(projectDirectory, "workspace.json");
        if (IsOurWorkspace(workspacePath)) File.Delete(workspacePath);
    }

    private static JsonObject BuildWorkspace(
        string projectDirectory,
        string projectName,
        string outputDirectory,
        IReadOnlyList<string> sources,
        string? builtinsJar,
        string javaStubJar)
    {
        var sourceRoots = sources
            .Where(File.Exists)
            .Select(path => Path.GetDirectoryName(Path.GetFullPath(path))!)
            .Distinct(StringComparer.Ordinal)
            .OrderBy(path => path, StringComparer.Ordinal)
            .Append(Path.Combine(outputDirectory, "stubs"))
            .Distinct(StringComparer.Ordinal)
            .ToArray();

        var dependencies = new JsonArray {
            new JsonObject { ["type"] = "moduleSource" },
            new JsonObject { ["type"] = "inheritedSdk" },
        };
        var libraries = new JsonArray();
        // The Kotlin core classifiers (`Any`, `Int`, `List`, ...) are the only thing still taken from
        // the JVM distribution, with Unit.class and Function.class for callbacks' JVM ABI; every other declaration,
        // including `kotlin.clr`, now comes from DotKt's
        // own CLR standard library KLIB through the projected archive.
        AddLibrary("Kotlin builtins", builtinsJar);
        AddLibrary("DotKt: CLR projection", javaStubJar);

        void AddLibrary(string name, string? path)
        {
            if (path is null || !File.Exists(path)) return;
            dependencies.Add(new JsonObject {
                ["type"] = "library",
                ["name"] = name,
                ["scope"] = "compile",
            });
            libraries.Add(new JsonObject {
                ["name"] = name,
                ["type"] = "COMPILE",
                ["roots"] = new JsonArray {
                    new JsonObject { ["path"] = Path.GetFullPath(path) },
                },
            });
        }

        var roots = new JsonArray();
        foreach (var sourceRoot in sourceRoots)
        {
            roots.Add(new JsonObject {
                ["path"] = sourceRoot,
                ["sourceRoots"] = new JsonArray {
                    new JsonObject {
                        ["path"] = sourceRoot,
                        ["type"] = "java-source",
                    },
                },
            });
        }

        var moduleName = ModulePrefix + projectName;
        return new JsonObject {
            ["modules"] = new JsonArray {
                new JsonObject {
                    ["name"] = moduleName,
                    ["dependencies"] = dependencies,
                    ["contentRoots"] = roots,
                },
            },
            ["libraries"] = libraries,
            ["kotlinSettings"] = new JsonArray {
                new JsonObject {
                    ["name"] = "Kotlin",
                    ["sourceRoots"] = new JsonArray(),
                    ["configFileItems"] = new JsonArray(),
                    ["module"] = moduleName,
                    ["useProjectSettings"] = false,
                    ["implementedModuleNames"] = new JsonArray(),
                    ["dependsOnModuleNames"] = new JsonArray(),
                    ["additionalVisibleModuleNames"] = new JsonArray(),
                    ["productionOutputPath"] = null,
                    ["testOutputPath"] = null,
                    ["sourceSetNames"] = new JsonArray(),
                    ["isTestModule"] = false,
                    ["externalProjectId"] = "",
                    ["isHmppEnabled"] = false,
                    ["pureKotlinSourceFolders"] = new JsonArray(),
                    ["kind"] = "default",
                    ["compilerArguments"] = "J{\"jvmTarget\":\"21\",\"autoAdvanceLanguageVersion\":false,\"autoAdvanceApiVersion\":false,\"apiVersion\":\"2.4\",\"languageVersion\":\"2.4\",\"companionBlocks\":true,\"companionBlocksAndExtensions\":true}",
                    // Explicitly enable companion blocks in the analyzer. Keep both serialized argument names
                    // for Kotlin 2.4 and newer LSP hosts; their compiler argument schema renamed the feature.
                    // additionalArguments also carries the current CLI spelling for settings consumers.
                    ["additionalArguments"] = "-Xjvm-default=all -Xcompanion-blocks",
                    ["scriptTemplates"] = null,
                    ["scriptTemplatesClasspath"] = null,
                    ["copyJsLibraryFiles"] = false,
                    ["outputDirectoryForJsLibraryFiles"] = null,
                    ["targetPlatform"] = "JVM (21)",
                    ["externalSystemRunTasks"] = new JsonArray(),
                    ["version"] = 5,
                    ["flushNeeded"] = false,
                },
            },
            // The singular output keys intentionally support both the current importer and the 262.9593.0 schema.
            ["javaSettings"] = new JsonArray {
                new JsonObject {
                    ["module"] = moduleName,
                    ["inheritedCompilerOutput"] = true,
                    ["excludeOutput"] = true,
                    ["compilerOutput"] = null,
                    ["compilerOutputForTests"] = null,
                    ["languageLevelId"] = "JDK_21",
                    ["manifestAttributes"] = new JsonObject(),
                },
            },
        };
    }

    private static void EnsureWorkspaceIsOurs(string path)
    {
        if (File.Exists(path) && !IsOurWorkspace(path))
            throw new InvalidOperationException(
                $"refusing to overwrite existing non-DotKtx workspace model '{path}'");
    }

    private static bool IsOurWorkspace(string path)
    {
        if (!File.Exists(path)) return false;
        try
        {
            using var document = JsonDocument.Parse(File.ReadAllText(path));
            return document.RootElement.TryGetProperty("modules", out var modules) &&
                modules.ValueKind == JsonValueKind.Array &&
                modules.EnumerateArray().Any(module =>
                    module.TryGetProperty("name", out var name) &&
                    name.GetString()?.StartsWith(ModulePrefix, StringComparison.Ordinal) == true);
        }
        catch (JsonException)
        {
            return false;
        }
    }

    private static void WriteTextIfDifferent(string path, string contents)
    {
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        if (File.Exists(path) && StringComparer.Ordinal.Equals(File.ReadAllText(path), contents)) return;
        var temporary = path + "." + Guid.NewGuid().ToString("N") + ".tmp";
        try
        {
            File.WriteAllText(temporary, contents, new UTF8Encoding(encoderShouldEmitUTF8Identifier: false));
            File.Move(temporary, path, overwrite: true);
        }
        finally
        {
            if (File.Exists(temporary)) File.Delete(temporary);
        }
    }

    private static void WriteBytesIfDifferent(string path, byte[] contents)
    {
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        if (File.Exists(path) && File.ReadAllBytes(path).AsSpan().SequenceEqual(contents)) return;
        var temporary = path + "." + Guid.NewGuid().ToString("N") + ".tmp";
        try
        {
            File.WriteAllBytes(temporary, contents);
            File.Move(temporary, path, overwrite: true);
        }
        finally
        {
            if (File.Exists(temporary)) File.Delete(temporary);
        }
    }

    private static void RemoveEmptyDirectories(string root)
    {
        foreach (var directory in Directory.EnumerateDirectories(root, "*", SearchOption.AllDirectories)
            .OrderByDescending(path => path.Length))
            if (!Directory.EnumerateFileSystemEntries(directory).Any())
                Directory.Delete(directory);
    }
}
